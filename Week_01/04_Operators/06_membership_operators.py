


# <========== Membership Operators ==========>

# IN Operators: "Returns True if value exists"
numbers = [5, 10, 15, 20, 25, 30]
print(30 in numbers)

# NOT IN Operators: "Returns True if value does not exists"
print(9 not in numbers)

