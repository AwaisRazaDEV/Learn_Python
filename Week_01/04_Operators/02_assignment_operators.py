
# Operators     |     Example     |     Equivalent
#    =          |      x = 3      |     Assign Value
#   +=          |      x += 3     |     x = x + 3
#   -=          |      x -= 3     |     x = x - 3
#   *=          |      x *= 3     |     x = x * 3
#   /=          |      x /= 3     |     x = x / 3
#   //=         |      x //= 3    |     x = x // 3
#   %=          |      x %= 3     |     x = x % 3
#   **=         |      x **= 3    |     x = x ** 3