

# <---------------- Join Two Tuples ---------------->
# To join two or more tuples you can use the + operator:

tuple_1 = ("red", "green", "yellow")
tuple_2 = (1, 2, 3, 4)
tuple_3 = tuple_1 + tuple_2
print(tuple_3)


# <---------------- Multiply Tuples ---------------->
# If you want to multiply the content of a tuple a given number of times, you can use the * operator:

tuple_4 = 2 * tuple_1
print(tuple_4)
